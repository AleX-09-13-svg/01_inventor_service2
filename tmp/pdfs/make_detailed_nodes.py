def text(x,y,s,size=10):
    p.insert_text((x,y),s,fontname='AR',fontsize=size,color=INK)
def line(x,y,a,b,w=.7,c=INK):
    p.draw_line((x,y),(a,b),color=c,width=w)
def rect(x,y,w,h,fill=None,hatch=False):
    p.draw_rect(F.Rect(x,y,x+w,y+h),color=INK,fill=fill,width=.8)
    if hatch:
        # Clip 45-degree hatch segments to the rectangle.
        for k in range(-int(h),int(w)+1,11):
            lo=max(0,-k); hi=min(h,w-k)
            if hi>lo: line(x+k+lo,y+lo,x+k+hi,y+hi,.25,GRAY)
def board(x,y,w,h):
    rect(x,y,w,h,WOOD,True)
def circle(x,y,r,fill=None):
    p.draw_circle((x,y),r,color=INK,fill=fill,width=.7)
def leader(x,y,a,b,s):
    circle(x,y,1.6,INK); line(x,y,a,b,.5); text(a+5,b-3,s)
def dh(x,a,y,e,s):
    line(x,e,x,y+4,.35); line(a,e,a,y+4,.35); line(x,y,a,y,.35)
    for k in (x,a): line(k-3,y+3,k+3,y-3,.6)
    text((x+a)/2-3*len(s),y-5,s,9)
def dv(y,b,x,e,s):
    line(e,y,x+4,y,.35);line(e,b,x+4,b,.35);line(x,y,x,b,.35)
    for k in (y,b): line(x-3,k+3,x+3,k-3,.6)
    text(x+5,(y+b)/2+3,s,9)
def screw(x,y,length):
    # Horizontal screw: head at x; thread towards positive x.
    rect(x,y-6,4,12,METAL); rect(x+4,y-2,length-8,4,METAL)
    line(x+length-4,y-2,x+length,y); line(x+length,y,x+length-4,y+2)
    for a in range(15,int(length)-4,7): line(x+a,y-4,x+a+4,y+4,.5)
    line(x+1,y-4,x+1,y+4,.5)
def screw_left(x,y,length):
    # Head on the mounted part, tip in the wall/substrate.
    rect(x-4,y-6,4,12,METAL)
    rect(x-length+8,y-2,length-12,4,METAL)
    line(x-length+8,y-2,x-length,y)
    line(x-length,y,x-length+8,y+2)
    for a in range(15,int(length)-8,7):
        line(x-a,y-4,x-a-4,y+4,.5)
    line(x-2,y-4,x-2,y+4,.5)
